    result.update({'score': round(score, 3), 'decision': decision, 'action': action, 'reason': reason, 'confidence': round(confidence, 4)})
    result['trace'] = trace
    result['policy_parameters'] = {'threshold': 55, 'window_hours': 160, 'max_capacity': 243}
    return result

