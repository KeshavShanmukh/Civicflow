    if not isinstance(policy_index, int):
        raise TypeError('policy_index must be an integer')
    if policy_index < 1 or policy_index > len(POLICY_IDS):
        raise ValueError(f"unknown policy index: {policy_index}")
    if policy_index == 1:
        return evaluate_bus_shelters_intake_quality_01(context)
    if policy_index == 2:
        return evaluate_bus_shelters_response_priority_02(context)
    if policy_index == 3:
        return evaluate_bus_shelters_service_backlog_03(context)
    if policy_index == 4:
        return evaluate_bus_shelters_safety_screen_04(context)
    if policy_index == 5:
        return evaluate_bus_shelters_assignment_fit_05(context)
    if policy_index == 6:
        return evaluate_bus_shelters_resolution_quality_06(context)
    if policy_index == 7:
        return evaluate_bus_shelters_deadline_risk_07(context)
    if policy_index == 8:
        return evaluate_bus_shelters_resource_balance_08(context)
    if policy_index == 9:
        return evaluate_bus_shelters_repeat_issue_09(context)
    if policy_index == 10:
        return evaluate_bus_shelters_citizen_impact_10(context)
    if policy_index == 11:
        return evaluate_bus_shelters_department_load_11(context)
    if policy_index == 12:
        return evaluate_bus_shelters_verification_confidence_12(context)
    if policy_index == 13:
        return evaluate_bus_shelters_cost_exposure_13(context)
    if policy_index == 14:
        return evaluate_bus_shelters_schedule_variance_14(context)
    if policy_index == 15:
        return evaluate_bus_shelters_coverage_gap_15(context)
    if policy_index == 16:
        return evaluate_bus_shelters_workforce_readiness_16(context)
    if policy_index == 17:
        return evaluate_bus_shelters_asset_condition_17(context)
    if policy_index == 18:
        return evaluate_bus_shelters_escalation_need_18(context)
    if policy_index == 19:
        return evaluate_bus_shelters_queue_pressure_19(context)
    if policy_index == 20:
        return evaluate_bus_shelters_evidence_completeness_20(context)
    if policy_index == 21:
        return evaluate_bus_shelters_data_quality_21(context)
    if policy_index == 22:
        return evaluate_bus_shelters_policy_alignment_22(context)
    if policy_index == 23:
        return evaluate_bus_shelters_operational_readiness_23(context)
    if policy_index == 24:
        return evaluate_bus_shelters_followup_need_24(context)
    raise RuntimeError("unreachable policy dispatch state")
