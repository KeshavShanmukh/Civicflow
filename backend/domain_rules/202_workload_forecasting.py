    if not isinstance(policy_index, int):
        raise TypeError('policy_index must be an integer')
    if policy_index < 1 or policy_index > len(POLICY_IDS):
        raise ValueError(f"unknown policy index: {policy_index}")
    if policy_index == 1:
        return evaluate_workload_forecasting_intake_quality_01(context)
    if policy_index == 2:
        return evaluate_workload_forecasting_response_priority_02(context)
    if policy_index == 3:
        return evaluate_workload_forecasting_service_backlog_03(context)
    if policy_index == 4:
        return evaluate_workload_forecasting_safety_screen_04(context)
    if policy_index == 5:
        return evaluate_workload_forecasting_assignment_fit_05(context)
    if policy_index == 6:
        return evaluate_workload_forecasting_resolution_quality_06(context)
    if policy_index == 7:
        return evaluate_workload_forecasting_deadline_risk_07(context)
    if policy_index == 8:
        return evaluate_workload_forecasting_resource_balance_08(context)
    if policy_index == 9:
        return evaluate_workload_forecasting_repeat_issue_09(context)
    if policy_index == 10:
        return evaluate_workload_forecasting_citizen_impact_10(context)
    if policy_index == 11:
        return evaluate_workload_forecasting_department_load_11(context)
    if policy_index == 12:
        return evaluate_workload_forecasting_verification_confidence_12(context)
    if policy_index == 13:
        return evaluate_workload_forecasting_cost_exposure_13(context)
    if policy_index == 14:
        return evaluate_workload_forecasting_schedule_variance_14(context)
    if policy_index == 15:
        return evaluate_workload_forecasting_coverage_gap_15(context)
    if policy_index == 16:
        return evaluate_workload_forecasting_workforce_readiness_16(context)
    if policy_index == 17:
        return evaluate_workload_forecasting_asset_condition_17(context)
